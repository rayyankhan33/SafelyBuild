// Runs every test suite and writes the real output to docs/test-results.md (evidence for the
// mid evaluation). Requires: PostgreSQL running (npm run db:start). The Node integration tests use
// the throw-away database "safelybuild_test"; they never touch demo data.
// Usage: npm run test:all
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const strip = (s) => s.replace(/\x1b\[[0-9;]*m/g, '');
const run = (cmd, args, cwd = root) => {
  const r = spawnSync(cmd, args, { cwd, encoding: 'utf8', shell: process.platform === 'win32' && cmd === 'npm' });
  return { code: r.status, out: strip((r.stdout ?? '') + (r.stderr ?? '')) };
};

const py = path.join(root, 'services/inference/.venv', process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python');
const suites = [
  ['API: unit + integration + schema (Node test runner, real PostgreSQL)', run('npm', ['test'])],
  ['Inference service (pytest)', run(py, ['-m', 'pytest', 'services/inference/tests', '-v', '--tb=short', '-p', 'no:cacheprovider'])],
];

let md = `# Test results\n\nGenerated by \`npm run test:all\` on ${new Date().toISOString()}. Raw output below; test IDs map to docs/srs.md.\n`;
let failed = false;
for (const [name, r] of suites) {
  if (r.code !== 0) failed = true;
  const summary = r.out.split('\n').filter((l) => /^ℹ (tests|pass|fail)|passed|failed/.test(l)).join('  ');
  md += `\n## ${name}\n\nExit code: ${r.code}. ${summary.trim()}\n\n\`\`\`\n${r.out.trim()}\n\`\`\`\n`;
}
fs.writeFileSync(path.join(root, 'docs/test-results.md'), md);
console.log(failed ? 'SOME TESTS FAILED - see docs/test-results.md' : 'All suites passed - results in docs/test-results.md');
process.exit(failed ? 1 : 0);
